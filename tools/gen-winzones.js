#!/usr/bin/env node
// Regenerates the Windows to IANA time zone table in
// runtime/src/lib/winzones.zig from the CLDR default mapping.
//
// Usage: node tools/gen-winzones.js [windowsZones.json-or-xml [cldr_version]]
//
// With no argument the script downloads windowsZones.json from the pinned
// CLDR release and verifies its SHA-256 digest (this needs curl). Passing a
// local windowsZones.json or windowsZones.xml regenerates offline from it.
// The script rewrites the leading doc comment and the `map` table of
// winzones.zig and keeps the rest of the file. CLDR data is under the
// Unicode license, which permits redistribution.

const fs = require("fs");
const os = require("os");
const path = require("path");
const crypto = require("crypto");
const {execFileSync} = require("child_process");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "runtime", "src", "lib", "winzones.zig");

const CLDR_VERSION = "48.2.1";
const CLDR_COMMIT = "26a79cb42bfcc90def764102aa2af126d9ef3108";
const CLDR_SHA256 = "fa1ee8731ff106b66c003b55af19313a2498bd34ab4ae6261fb937c0b34f21d1";
const URL =
  `https://raw.githubusercontent.com/unicode-org/cldr-json/${CLDR_COMMIT}` +
  "/cldr-json/cldr-core/supplemental/windowsZones.json";

function fetchPinned() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "lus-winzones-"));
  const file = path.join(tmp, "windowsZones.json");
  try {
    execFileSync("curl", ["-fsSL", "--max-time", "60", URL, "-o", file], {stdio: "inherit"});
    const input = fs.readFileSync(file, "utf-8");
    const digest = crypto.createHash("sha256").update(input).digest("hex");
    if (digest !== CLDR_SHA256) {
      console.error(`error: ${URL} has SHA-256 ${digest}, expected ${CLDR_SHA256}`);
      process.exit(1);
    }
    return input;
  } finally {
    fs.rmSync(tmp, {recursive: true, force: true});
  }
}

let input;
let sourceVersion;
if (process.argv[2]) {
  input = fs.readFileSync(process.argv[2], "utf-8");
  sourceVersion = process.argv[3] || "unknown";
} else {
  input = fetchPinned();
  sourceVersion = CLDR_VERSION;
}

// The default territory ("001") supplies one primary IANA zone per Windows
// zone key. A type value may list several zones, and the first is primary.
const pairs = [];
if (input.trimStart().startsWith("{")) {
  const data = JSON.parse(input);
  if (sourceVersion === "unknown") sourceVersion = data.supplemental?.version?._cldrVersion || "unknown";
  const entries = data.supplemental?.windowsZones?.mapTimezones;
  if (!Array.isArray(entries)) throw new Error("CLDR JSON has no windowsZones.mapTimezones array");
  for (const entry of entries) {
    const zone = entry.mapZone;
    if (zone?._territory === "001") pairs.push({win: zone._other, iana: zone._type.split(/\s+/)[0]});
  }
} else {
  const re = /<mapZone\s+other="([^"]+)"\s+territory="001"\s+type="([^"]+)"/g;
  let match;
  while ((match = re.exec(input)) !== null) pairs.push({win: match[1], iana: match[2].split(/\s+/)[0]});
}
if (pairs.length === 0) throw new Error("CLDR input contains no default Windows zone mappings");
for (const p of pairs) {
  if (!/^[\x20-\x7e]+$/.test(p.win + p.iana)) throw new Error(`non ASCII zone name: ${p.win} ${p.iana}`);
}
pairs.sort((a, b) => (a.win < b.win ? -1 : a.win > b.win ? 1 : 0));

let head =
  "//! The mapping from Windows time zone keys to IANA zone names, used by\n" +
  `//! \`time.localzone\` on Windows. The table is the CLDR ${sourceVersion} default\n` +
  `//! mapping (${pairs.length} entries), generated by \`tools/gen-winzones.js\`.\n` +
  "//! Run `mise run gen:winzones` to regenerate it.\n" +
  "\n" +
  "const std = @import(\"std\");\n" +
  "const builtin = @import(\"builtin\");\n" +
  "\n" +
  "pub const map = [_]struct { []const u8, []const u8 }{\n";
for (const p of pairs) head += `    .{ ${JSON.stringify(p.win)}, ${JSON.stringify(p.iana)} },\n`;
head += "};\n";

const current = fs.readFileSync(OUT, "utf-8");
const start = current.indexOf("pub const map = ");
const end = start < 0 ? -1 : current.indexOf("\n};\n", start);
if (end < 0) throw new Error(`${OUT} has no \`pub const map\` table`);
fs.writeFileSync(OUT, head + current.slice(end + 4));
console.log(`Wrote runtime/src/lib/winzones.zig: CLDR ${sourceVersion}, ${pairs.length} mappings.`);
