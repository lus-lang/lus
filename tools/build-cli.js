#!/usr/bin/env node
// Generates the usage text, the shell completions, and the man pages of
// the `lus` command line from spec/tools/cli.json, and checks that the
// option parsers of the runtime and the CLI page of the manual agree with
// it. Run: node tools/build-cli.js [--check]
//
// spec/tools/cli.json describes the default command `run`, whose options
// are those of `lus` itself, and every other command. A command has a
// `name`, a one-line `summary`, its `synopsis` lines after `lus NAME`,
// its `options`, its `positionals`, its `subcommands`, and its `exit`
// statuses. An option has its `names` (a short form such as `-o`, a long
// form such as `--output`, or both), a `summary`, and a `value` when it
// takes one. A value has a `name` for the usage text and a `kind` that
// the completions read: `file`, `dir`, `path` (a file or a directory),
// `script` (a .lus file), `enum` with its `values`, `permission`,
// `installed` (an installed release), `number`, or `text`. A `hidden`
// option is accepted but left out of the usage text, the completions,
// and the man pages. Every command except one with `"help": false` also
// accepts `-h` and `--help`.
//
// The outputs:
//
// - runtime/src/tools/usage.zig: the usage text that each command prints
//   for --help and after a usage error, and the option table of `lus`.
// - packaging/share: the tree that `zig build install` copies into the
//   prefix, at the paths that distributions use: man/man1 for the man
//   pages, bash-completion/completions, zsh/site-functions, and
//   fish/vendor_completions.d for the completions, and powershell for the
//   PowerShell script. `lus completions SHELL` prints the same scripts.
//
// The man pages take their prose from packages/site/src/manual/cli.mdx:
// `lus.1` from the section `## lus` and `lus-NAME.1` from `## lus NAME`.

const fs = require("fs");
const path = require("path");
const { readPermissions } = require("./build-facts.js");

const ROOT = path.join(__dirname, "..");
const read = (root, rel) => fs.readFileSync(path.join(root, rel), "utf8");
const SOURCE = "spec/tools/cli.json";
const MANUAL = "packages/site/src/manual/cli.mdx";

function loadSpec(root = ROOT) {
  return JSON.parse(read(root, SOURCE));
}

/// The commands that print usage for -h and --help.
const hasHelp = (cmd) => cmd.help !== false;

/// The visible options of a command, with -h and --help added where the
/// command accepts them and lists no option of its own for them.
function visibleOptions(cmd, withHelp = true) {
  const opts = (cmd.options ?? []).filter((o) => !o.hidden);
  if (withHelp && hasHelp(cmd) && !opts.some((o) => o.names.includes("--help"))) {
    opts.push({ names: ["-h", "--help"], summary: "print this help and exit" });
  }
  return opts;
}

// ---------------------------------------------------------------------
// Usage text

function synopsisLines(spec, cmd) {
  const lines = [];
  if (cmd.default) for (const s of spec.synopsis) lines.push(`lus ${s}`);
  else for (const s of cmd.synopsis) lines.push(s.startsWith("+") ? `lus ${s}` : `lus ${cmd.name} ${s}`);
  return lines;
}

function optionLabel(o) {
  const label = o.names.join(", ");
  if (!o.value) return label;
  return o.value.optional ? `${label} [${o.value.name}]` : `${label} ${o.value.name}`;
}

function table(rows) {
  const width = Math.min(28, Math.max(...rows.map(([l]) => l.length)) + 2);
  return rows.map(([l, r]) => (l.length + 2 > width ? `  ${l}\n  ${" ".repeat(width)}${r}` : `  ${l.padEnd(width)}${r}`)).join("\n");
}

function sentence(text) {
  return text[0].toUpperCase() + text.slice(1) + ".";
}

function usageText(spec, cmd) {
  const lines = synopsisLines(spec, cmd);
  let text = `usage: ${lines[0]}\n` + lines.slice(1).map((l) => `       ${l}\n`).join("");
  text += "\n" + sentence(cmd.default ? spec.summary : cmd.summary) + "\n";
  if (cmd.default) {
    text += "\nCommands:\n" + table(spec.commands.map((c) => [c.name, c.summary])) + "\n";
  }
  if (cmd.subcommands) {
    const label = (s) => [s.name, ...(s.options ?? []).map((o) => `[${optionLabel(o)}]`), ...(s.positionals ?? []).map(positionalLabel)].join(" ");
    text += "\nCommands:\n" + table(cmd.subcommands.map((s) => [label(s), s.summary])) + "\n";
  }
  const opts = visibleOptions(cmd).map((o) => [optionLabel(o), o.summary]);
  for (const s of cmd.separators ?? []) opts.push([s.name, s.summary]);
  if (opts.length) text += "\nOptions:\n" + table(opts) + "\n";
  return text;
}

function positionalLabel(p) {
  const name = p.repeat ? `${p.name} ...` : p.name;
  return p.optional ? `[${name}]` : name;
}

function zigString(text) {
  return JSON.stringify(text);
}

function usageZig(spec) {
  let out = "//! Generated by tools/build-cli.js from spec/tools/cli.json. Do not edit.\n";
  out += "//!\n//! The usage text that each command prints for `--help` and after a\n//! usage error, with the option table of `lus` itself.\n\n";
  out += 'const std = @import("std");\n\n';
  out += "pub const Command = struct { name: []const u8, usage: []const u8 };\n\n";
  out += "pub const commands = [_]Command{\n";
  for (const c of spec.commands) out += `    .{ .name = ${zigString(c.name)}, .usage = ${zigString(usageText(spec, c))} },\n`;
  out += "};\n\n";
  out += "/// The usage text of the command `name`.\n";
  out += "pub fn of(comptime name: []const u8) []const u8 {\n";
  out += "    inline for (commands) |c| {\n";
  out += "        if (comptime std.mem.eql(u8, c.name, name)) return c.usage;\n";
  out += "    }\n";
  out += '    @compileError("no command named " ++ name);\n';
  out += "}\n\n";
  out += "/// One option of `lus`: its short letter, its long name, and whether it\n/// takes a value.\n";
  out += "pub const Option = struct { short: ?u8, long: ?[]const u8, takes_value: bool };\n\n";
  out += "pub const run_options = [_]Option{\n";
  const run = spec.commands.find((c) => c.default);
  for (const o of run.options) {
    const short = o.names.find((n) => /^-[^-]$/.test(n));
    const long = o.names.find((n) => n.startsWith("--"));
    out += `    .{ .short = ${short ? `'${short[1]}'` : "null"}, .long = ${long ? zigString(long.slice(2)) : "null"}, .takes_value = ${o.value ? "true" : "false"} },\n`;
  }
  out += "};\n";
  return out;
}

// ---------------------------------------------------------------------
// Completions

/// Every option of a command, its subcommands included, as one list of
/// [names, value, summary, subcommand].
function completionOptions(cmd) {
  const opts = visibleOptions(cmd).map((o) => ({ ...o, sub: null }));
  for (const s of cmd.subcommands ?? []) for (const o of s.options ?? []) opts.push({ ...o, sub: s.name });
  return opts;
}

function valuesOf(v, perms) {
  if (v.kind === "enum") return v.values;
  if (v.kind === "permission") return perms;
  return null;
}

const sq = (s) => `'${s.replace(/'/g, `'\\''`)}'`;

function bash(spec, perms) {
  const names = spec.commands.map((c) => c.name);
  let out = "# Generated by tools/build-cli.js from spec/tools/cli.json. Do not edit.\n";
  out += "# Completion of the lus command line for bash.\n\n";
  out += "_lus_value() {\n";
  out += "    local IFS=$'\\n'\n";
  out += '    case "$1" in\n';
  out += '        file | path) COMPREPLY=($(compgen -f -- "$cur")) && compopt -o filenames 2>/dev/null ;;\n';
  out += '        dir) COMPREPLY=($(compgen -d -- "$cur")) && compopt -o filenames 2>/dev/null ;;\n';
  out += "        script) COMPREPLY=($(compgen -f -X '!*.lus' -- \"$cur\") $(compgen -d -- \"$cur\")) && compopt -o filenames 2>/dev/null ;;\n";
  out += "        installed) COMPREPLY=($(compgen -W \"$(lus version list 2>/dev/null | awk '{print $1}')\" -- \"$cur\")) ;;\n";
  out += "        words) COMPREPLY=($(IFS=' ' && compgen -W \"$2\" -- \"$cur\")) ;;\n";
  out += "        *) COMPREPLY=() ;;\n";
  out += "    esac\n";
  out += "}\n\n";
  out += "_lus() {\n";
  out += "    local cur prev words cword\n";
  out += "    if declare -F _init_completion >/dev/null 2>&1; then\n";
  out += "        _init_completion -n := || return\n";
  out += "    else\n";
  out += '        cur=${COMP_WORDS[COMP_CWORD]}\n';
  out += '        prev=${COMP_WORDS[COMP_CWORD - 1]}\n';
  out += '        words=("${COMP_WORDS[@]}")\n';
  out += "        cword=$COMP_CWORD\n";
  out += "    fi\n";
  out += `    local commands=${sq(names.join(" "))}\n`;
  out += "    local cmd=run start=1 sub=\n";
  out += '    if [[ $cword -gt 1 && " $commands " == *" ${words[1]} "* ]]; then\n';
  out += "        cmd=${words[1]}\n";
  out += "        start=2\n";
  out += "    fi\n";
  // Subcommands.
  const withSubs = spec.commands.filter((c) => c.subcommands);
  if (withSubs.length) {
    out += '    case "$cmd" in\n';
    for (const c of withSubs) {
      const subs = c.subcommands.map((s) => s.name).join(" ");
      out += `        ${c.name})\n`;
      out += `            local w\n`;
      out += `            for ((w = start; w < cword; w++)); do\n`;
      out += `                if [[ " ${subs} " == *" \${words[w]} "* ]]; then\n`;
      out += `                    sub=\${words[w]}\n`;
      out += `                    start=$((w + 1))\n`;
      out += `                    break\n`;
      out += `                fi\n`;
      out += `            done\n`;
      out += `            ;;\n`;
    }
    out += "    esac\n";
  }
  // The value of the option before the cursor.
  out += '    case "$cmd:$prev" in\n';
  for (const c of spec.commands) {
    for (const o of completionOptions(c)) {
      if (!o.value) continue;
      const pats = o.names.map((n) => `${c.name}:${n}`).join(" | ");
      const vals = valuesOf(o.value, perms);
      const action = vals ? `_lus_value words ${sq(vals.join(" "))}` : `_lus_value ${o.value.kind}`;
      out += `        ${pats})\n            ${action}\n            return\n            ;;\n`;
    }
  }
  out += "    esac\n";
  // Options.
  out += "    if [[ $cur == -* ]]; then\n";
  out += '        case "$cmd:$sub" in\n';
  for (const c of spec.commands) {
    const opts = completionOptions(c);
    const base = opts.filter((o) => !o.sub).flatMap((o) => o.names);
    out += `            ${c.name}:) _lus_value words ${sq(base.join(" "))} ;;\n`;
    for (const s of c.subcommands ?? []) {
      const all = base.concat(opts.filter((o) => o.sub === s.name).flatMap((o) => o.names));
      out += `            ${c.name}:${s.name}) _lus_value words ${sq(all.join(" "))} ;;\n`;
    }
  }
  out += "        esac\n";
  out += "        return\n";
  out += "    fi\n";
  // The first argument of `lus` is a command or a script.
  out += "    if [[ $cmd == run && $start -eq 1 && $cword -eq 1 ]]; then\n";
  out += "        _lus_value script\n";
  out += "        local IFS=$'\\n'\n";
  out += '        COMPREPLY+=($(compgen -W "${commands// /$\'\\n\'}" -- "$cur"))\n';
  out += "        return\n";
  out += "    fi\n";
  // Positionals: count the words since the command that are neither an
  // option nor the value of one.
  out += "    local n=0 i takes\n";
  out += '    case "$cmd" in\n';
  for (const c of spec.commands) {
    const takes = completionOptions(c).filter((o) => o.value && !o.value.optional).flatMap((o) => o.names);
    out += `        ${c.name}) takes=${sq(takes.join(" "))} ;;\n`;
  }
  out += "    esac\n";
  out += "    for ((i = start; i < cword; i++)); do\n";
  out += '        if [[ " $takes " == *" ${words[i]} "* ]]; then\n';
  out += "            ((i++))\n";
  out += "        elif [[ ${words[i]} != -* ]]; then\n";
  out += "            ((n++))\n";
  out += "        fi\n";
  out += "    done\n";
  out += '    case "$cmd:$sub" in\n';
  const positionalCase = (label, list) => {
    if (!list.length) return `        ${label}) COMPREPLY=() ;;\n`;
    let s = `        ${label})\n            case $n in\n`;
    list.forEach((p, i) => {
      const vals = valuesOf(p, perms);
      const action = vals ? `_lus_value words ${sq(vals.join(" "))}` : `_lus_value ${p.kind}`;
      const pat = i === list.length - 1 && p.repeat ? "*" : String(i);
      s += `                ${pat}) ${action} ;;\n`;
    });
    if (!list[list.length - 1].repeat) s += "                *) COMPREPLY=() ;;\n";
    s += "            esac\n            ;;\n";
    return s;
  };
  for (const c of spec.commands) {
    if (c.subcommands) {
      out += `        ${c.name}:) _lus_value words ${sq(c.subcommands.map((s) => s.name).join(" "))} ;;\n`;
      for (const s of c.subcommands) out += positionalCase(`${c.name}:${s.name}`, s.positionals ?? []);
    } else {
      // `lus script args` counts the script, which `lus run script` names
      // after the command.
      out += positionalCase(`${c.name}:`, c.positionals ?? []);
    }
  }
  out += "    esac\n";
  out += "}\n\n";
  out += "complete -F _lus lus\n";
  return out;
}

function zshEscape(text) {
  return text.replace(/\\/g, "\\\\").replace(/'/g, `'\\''`).replace(/\[/g, "\\[").replace(/\]/g, "\\]");
}

function zshMessage(name) {
  return name.replace(/\[[^\]]*\]/g, "").replace(/:/g, "") || name.replace(/[[\]:]/g, "");
}

function zshAction(v, perms) {
  if (v.kind === "enum") return `(${v.values.join(" ")})`;
  if (v.kind === "permission") return "_lus_permissions";
  if (v.kind === "installed") return "_lus_installed";
  if (v.kind === "file" || v.kind === "path") return "_files";
  if (v.kind === "dir") return "_files -/";
  if (v.kind === "script") return "_files -g \"*.lus\"";
  return " ";
}

function zshOption(o, perms) {
  const desc = `[${zshEscape(o.summary)}]`;
  const value = o.value ? `${o.value.optional ? "::" : ":"}${zshMessage(o.value.name)}:${zshAction(o.value, perms)}` : "";
  const repeat = o.repeat ? "*" : "";
  if (o.names.length === 1) return `'${repeat}${o.names[0]}${desc}${value}'`;
  const excl = o.repeat ? "" : `(${o.names.join(" ")})`;
  return `'${excl}${repeat}'{${o.names.join(",")}}'${desc}${value}'`;
}

function zshPositional(p, perms) {
  const msg = zshMessage(p.name);
  const action = zshAction(p, perms);
  if (p.repeat) return `'*:${msg}:${action}'`;
  return `'${p.optional ? "::" : ":"}${msg}:${action}'`;
}

function zsh(spec, perms) {
  const fn = (c) => `_lus_${c.name}`;
  let out = "#compdef lus\n";
  out += "# Generated by tools/build-cli.js from spec/tools/cli.json. Do not edit.\n";
  out += "# Completion of the lus command line for zsh.\n\n";
  out += "_lus_permissions() {\n";
  out += `    compadd -- ${perms.join(" ")}\n`;
  out += "}\n\n";
  out += "_lus_installed() {\n";
  out += "    local -a releases\n";
  out += "    releases=(${${(f)\"$(_call_program releases lus version list 2>/dev/null)\"}%% *})\n";
  out += "    compadd -a releases\n";
  out += "}\n\n";
  out += "_lus_commands() {\n";
  out += "    local -a commands\n";
  out += "    commands=(\n";
  for (const c of spec.commands) out += `        '${c.name}:${zshEscape(c.summary)}'\n`;
  out += "    )\n";
  out += "    _describe -t commands command commands\n";
  out += "}\n\n";
  for (const c of spec.commands) {
    const opts = visibleOptions(c).map((o) => zshOption(o, perms));
    out += `${fn(c)}() {\n`;
    if (c.subcommands) {
      out += "    local curcontext=\"$curcontext\" state line ret=1\n";
      out += `    _arguments -C -s -S \\\n`;
      for (const o of opts) out += `        ${o} \\\n`;
      out += "        '1: :->sub' \\\n";
      out += "        '*:: :->args' && ret=0\n";
      out += "    case $state in\n";
      out += "        sub)\n";
      out += "            local -a subs\n";
      out += `            subs=(${c.subcommands.map((s) => `'${s.name}:${zshEscape(s.summary)}'`).join(" ")})\n`;
      out += "            _describe -t commands command subs && ret=0\n";
      out += "            ;;\n";
      out += "        args)\n";
      out += "            case $words[1] in\n";
      for (const s of c.subcommands) {
        const specs = opts.concat((s.options ?? []).map((o) => zshOption(o, perms))).concat((s.positionals ?? []).map((p) => zshPositional(p, perms)));
        out += `                ${s.name})\n`;
        out += specs.length ? `                    _arguments -s -S ${specs.join(" ")} && ret=0\n` : "                    ret=0\n";
        out += "                    ;;\n";
      }
      out += "            esac\n";
      out += "            ;;\n";
      out += "    esac\n";
      out += "    return ret\n";
    } else {
      const specs = opts.concat((c.positionals ?? []).map((p) => zshPositional(p, perms)));
      out += `    _arguments -s -S \\\n`;
      out += specs.map((s) => `        ${s}`).join(" \\\n") + "\n";
    }
    out += "}\n\n";
  }
  const run = spec.commands.find((c) => c.default);
  out += "_lus() {\n";
  out += "    local curcontext=\"$curcontext\" state line ret=1\n";
  out += "    _arguments -C -s -S \\\n";
  for (const o of visibleOptions(run)) out += `        ${zshOption(o, perms)} \\\n`;
  out += "        '1: :->first' \\\n";
  out += "        '*:: :->rest' && ret=0\n";
  out += "    case $state in\n";
  out += "        first)\n";
  out += "            _alternative 'commands:command:_lus_commands' 'scripts:script:_files -g \"*.lus\"' && ret=0\n";
  out += "            ;;\n";
  out += "        rest)\n";
  out += "            case $words[1] in\n";
  for (const c of spec.commands) out += `                ${c.name}) ${fn(c)} && ret=0 ;;\n`;
  out += "                *) _files && ret=0 ;;\n";
  out += "            esac\n";
  out += "            ;;\n";
  out += "    esac\n";
  out += "    return ret\n";
  out += "}\n\n";
  out += 'if [ "$funcstack[1]" = "_lus" ]; then\n';
  out += '    _lus "$@"\n';
  out += "else\n";
  out += "    compdef _lus lus\n";
  out += "fi\n";
  return out;
}

function fishValue(v, perms) {
  if (v.kind === "file" || v.kind === "path" || v.kind === "script") return "-r -F";
  if (v.kind === "dir") return "-x -a '(__fish_complete_directories)'";
  if (v.kind === "installed") return "-x -a '(__lus_installed)'";
  const vals = valuesOf(v, perms);
  if (vals) return `-x -a ${sq(vals.join(" "))}`;
  return "-x";
}

function fishOption(cond, o, perms) {
  const parts = [`complete -c lus -n ${sq(cond)}`];
  for (const n of o.names) parts.push(n.startsWith("--") ? `-l ${n.slice(2)}` : `-s ${n.slice(1)}`);
  if (o.value) parts.push(fishValue(o.value, perms));
  parts.push(`-d ${sq(o.summary)}`);
  return parts.join(" ") + "\n";
}

function fish(spec, perms) {
  const names = spec.commands.map((c) => c.name).join(" ");
  let out = "# Generated by tools/build-cli.js from spec/tools/cli.json. Do not edit.\n";
  out += "# Completion of the lus command line for fish.\n\n";
  out += "# The command of the command line: its first argument when that names a\n# command, otherwise run.\n";
  out += "function __lus_command\n";
  out += "    set -l tokens (commandline -opc)\n";
  out += `    if set -q tokens[2]; and contains -- $tokens[2] ${names}\n`;
  out += "        echo $tokens[2]\n";
  out += "    else\n";
  out += "        echo run\n";
  out += "    end\n";
  out += "end\n\n";
  out += "function __lus_using\n";
  out += "    test (__lus_command) = $argv[1]\n";
  out += "end\n\n";
  out += "# True when the command is $argv[1] and its subcommand is $argv[2].\n";
  out += "function __lus_sub\n";
  out += "    set -l tokens (commandline -opc)\n";
  out += "    __lus_using $argv[1]; or return 1\n";
  out += "    set -q tokens[3]; or return 1\n";
  out += "    test $tokens[3] = $argv[2]\n";
  out += "end\n\n";
  out += "# True when the command is $argv[1] and the command line names none of\n# its subcommands $argv[2..] yet.\n";
  out += "function __lus_no_sub\n";
  out += "    set -l tokens (commandline -opc)\n";
  out += "    __lus_using $argv[1]; or return 1\n";
  out += "    set -q tokens[3]; or return 0\n";
  out += "    not contains -- $tokens[3] $argv[2..]\n";
  out += "end\n\n";
  out += "function __lus_installed\n";
  out += "    lus version list 2>/dev/null | string replace -r ' .*' ''\n";
  out += "end\n\n";
  for (const c of spec.commands) {
    out += `\n# lus ${c.name}\n`;
    out += `complete -c lus -n 'test (count (commandline -opc)) -eq 1' -a ${c.name} -d ${sq(c.summary)}\n`;
    const cond = `__lus_using ${c.name}`;
    for (const o of visibleOptions(c)) out += fishOption(cond, o, perms);
    const fileish = (p) => ["file", "path", "script", "dir"].includes(p.kind);
    if (c.subcommands) {
      const subs = c.subcommands.map((s) => s.name);
      out += `complete -c lus -n ${sq(`__lus_no_sub ${c.name} ${subs.join(" ")}`)} -f\n`;
      for (const s of c.subcommands) {
        out += `complete -c lus -n ${sq(`__lus_no_sub ${c.name} ${subs.join(" ")}`)} -a ${s.name} -d ${sq(s.summary)}\n`;
        const sc = `__lus_sub ${c.name} ${s.name}`;
        for (const o of s.options ?? []) out += fishOption(sc, o, perms);
        const ps = s.positionals ?? [];
        if (!ps.some(fileish)) out += `complete -c lus -n ${sq(sc)} -f\n`;
        for (const p of ps) {
          if (p.kind === "installed") out += `complete -c lus -n ${sq(sc)} -a '(__lus_installed)'\n`;
          const vals = valuesOf(p, perms);
          if (vals) out += `complete -c lus -n ${sq(sc)} -a ${sq(vals.join(" "))}\n`;
        }
      }
    } else if (!c.default) {
      const ps = c.positionals ?? [];
      if (!ps.some(fileish)) out += `complete -c lus -n ${sq(cond)} -f\n`;
      for (const p of ps) {
        const vals = valuesOf(p, perms);
        if (vals) out += `complete -c lus -n ${sq(cond)} -a ${sq(vals.join(" "))}\n`;
      }
    }
  }
  return out;
}

const psq = (s) => `'${s.replace(/'/g, "''")}'`;

function powershell(spec, perms) {
  const valueTable = (v) => {
    const vals = valuesOf(v, perms);
    return `@{ Kind = ${psq(v.kind)}; Values = @(${(vals ?? []).map(psq).join(", ")}) }`;
  };
  const optTable = (o) => `@{ Names = @(${o.names.map(psq).join(", ")}); Summary = ${psq(o.summary)}; Value = ${o.value ? valueTable(o.value) : "$null"} }`;
  const posList = (ps) => `@(${(ps ?? []).map((p) => `@{ Kind = ${psq(p.kind)}; Values = @(${(valuesOf(p, perms) ?? []).map(psq).join(", ")}); Repeat = $${p.repeat ? "true" : "false"} }`).join(", ")})`;
  let out = "# Generated by tools/build-cli.js from spec/tools/cli.json. Do not edit.\n";
  out += "# Completion of the lus command line for PowerShell. Load it from the\n# profile with: lus completions powershell | Out-String | Invoke-Expression\n\n";
  out += "$lusCommands = [ordered]@{\n";
  for (const c of spec.commands) {
    out += `    ${psq(c.name)} = @{\n`;
    out += `        Summary = ${psq(c.summary)}\n`;
    out += `        Options = @(\n`;
    for (const o of visibleOptions(c)) out += `            ${optTable(o)}\n`;
    out += `        )\n`;
    out += `        Positionals = ${posList(c.positionals)}\n`;
    out += `        Subcommands = [ordered]@{\n`;
    for (const s of c.subcommands ?? []) {
      out += `            ${psq(s.name)} = @{ Summary = ${psq(s.summary)}; Options = @(${(s.options ?? []).map(optTable).join(", ")}); Positionals = ${posList(s.positionals)} }\n`;
    }
    out += `        }\n`;
    out += `    }\n`;
  }
  out += "}\n\n";
  out += String.raw`Register-ArgumentCompleter -Native -CommandName lus, lus.exe -ScriptBlock ({
    param($wordToComplete, $commandAst, $cursorPosition)
    $words = @($commandAst.CommandElements | Where-Object { $_.Extent.EndOffset -le $cursorPosition } | ForEach-Object { $_.ToString() })
    if ($wordToComplete -ne '' -and $words.Count -gt 0) { $words = @($words | Select-Object -First ($words.Count - 1)) }
    $name = 'run'
    $start = 1
    if ($words.Count -gt 1 -and $lusCommands.Contains($words[1])) {
        $name = $words[1]
        $start = 2
    }
    $command = $lusCommands[$name]
    $options = @($command.Options)
    $positionals = @($command.Positionals)
    $subcommand = $null
    if ($command.Subcommands.Count -gt 0) {
        for ($i = $start; $i -lt $words.Count; $i++) {
            if ($command.Subcommands.Contains($words[$i])) {
                $subcommand = $command.Subcommands[$words[$i]]
                $options += @($subcommand.Options)
                $positionals = @($subcommand.Positionals)
                $start = $i + 1
                break
            }
        }
    }
    $results = New-Object System.Collections.Generic.List[object]
    $add = {
        param($text, $tip)
        if ($text -like "$wordToComplete*") {
            if (-not $tip) { $tip = $text }
            $results.Add([System.Management.Automation.CompletionResult]::new($text, $text, 'ParameterValue', $tip))
        }
    }
    $values = {
        param($kind, $list)
        if ($kind -eq 'installed') {
            foreach ($line in @(& lus version list 2>$null)) { & $add ($line -split ' ')[0] $null }
        } else {
            foreach ($v in $list) { & $add $v $null }
        }
    }
    $previous = if ($words.Count -gt 0) { $words[$words.Count - 1] } else { '' }
    $taking = $options | Where-Object { $_.Value -and $_.Names -contains $previous } | Select-Object -First 1
    if ($taking) {
        & $values $taking.Value.Kind $taking.Value.Values
        return $results
    }
    if ($wordToComplete.StartsWith('-')) {
        foreach ($o in $options) { foreach ($n in $o.Names) { & $add $n $o.Summary } }
        return $results
    }
    if ($name -eq 'run' -and $start -eq 1 -and $words.Count -eq 1) {
        foreach ($key in $lusCommands.Keys) { & $add $key $lusCommands[$key].Summary }
        return $results
    }
    if ($command.Subcommands.Count -gt 0 -and -not $subcommand) {
        foreach ($key in $command.Subcommands.Keys) { & $add $key $command.Subcommands[$key].Summary }
        return $results
    }
    $n = 0
    for ($i = $start; $i -lt $words.Count; $i++) {
        $w = $words[$i]
        if ($options | Where-Object { $_.Value -and -not $_.Value.Optional -and $_.Names -contains $w }) { $i++ }
        elseif (-not $w.StartsWith('-')) { $n++ }
    }
    if ($positionals.Count -gt 0) {
        $p = if ($n -lt $positionals.Count) { $positionals[$n] } elseif ($positionals[$positionals.Count - 1].Repeat) { $positionals[$positionals.Count - 1] } else { $null }
        if ($p) { & $values $p.Kind $p.Values }
    }
    return $results
}.GetNewClosure())
`;
  return out;
}

