// Man pages

function roffEscape(text) {
  return text.replace(/\\/g, "\\e");
}

function roffCode(text) {
  return roffEscape(text).replace(/-/g, "\\-");
}

/// Converts the inline Markdown of the manual to roff.
function roffInline(text) {
  let out = "";
  const re = /``\s?([^`]+?)\s?``|`([^`]+)`|\[([^\]]+)\]\([^)]+\)|\*\*([^*]+)\*\*/g;
  let last = 0;
  for (const m of text.matchAll(re)) {
    out += roffEscape(text.slice(last, m.index));
    if (m[1] !== undefined || m[2] !== undefined) out += `\\fB${roffCode(m[1] ?? m[2])}\\fR`;
    else if (m[3] !== undefined) out += roffInline(m[3]);
    else out += `\\fB${roffEscape(m[4])}\\fR`;
    last = m.index + m[0].length;
  }
  return out + roffEscape(text.slice(last));
}

/// One sentence per line, as roff sources are written, with a line that
/// would start with a control character protected.
function roffPara(text) {
  return roffInline(text)
    .split(/(?<=\.) (?=[A-Z\\])/)
    .map((l) => (/^[.']/.test(l) ? `\\&${l}` : l))
    .join("\n");
}

function roffBlocks(list) {
  let out = "";
  for (const b of list) {
    if (b.type === "para") out += `.PP\n${roffPara(b.text)}\n`;
    else if (b.type === "code") out += `.PP\n.RS 4\n.nf\n${b.lines.map((l) => `\\&${roffCode(l)}`).join("\n")}\n.fi\n.RE\n`;
    else if (b.type === "table") for (const r of b.rows) out += `.TP\n${roffInline(r[0])}\n${roffPara(r[1])}\n`;
  }
  return out;
}

function manPage(spec, cmd, sections, site) {
  const page = cmd.default ? "lus" : `lus-${cmd.name}`;
  const heading = cmd.default ? "lus" : `lus ${cmd.name}`;
  const list = blocks(sections.get(heading));
  let out = `.\\" Generated by tools/build-cli.js from ${SOURCE} and ${MANUAL}. Do not edit.\n`;
  out += `.TH ${page.toUpperCase()} 1 "" "Lus" "Lus Manual"\n`;
  out += `.SH NAME\n${page} \\- ${roffEscape(cmd.default ? spec.summary : cmd.summary)}\n`;
  out += ".SH SYNOPSIS\n.nf\n";
  for (const line of synopsisLines(spec, cmd)) {
    const [, name, rest] = line.match(cmd.default ? /^(lus)(.*)$/ : /^(lus(?: [a-z]+)?)(.*)$/);
    out += `\\fB${name}\\fR${roffCode(rest)}\n`;
  }
  out += ".fi\n";
  // The blocks before the first `###` heading describe the command. An
  // options table and a table of commands get sections of their own, and
  // every `###` heading becomes a section, except the exit status, which
  // comes from the source.
  const description = [];
  const extra = [];
  let target = description;
  let title = null;
  for (const b of list) {
    if (b.type === "heading") {
      title = b.text;
      target = [];
      extra.push({ title: b.text, list: target });
      continue;
    }
    if (b.type === "table" && title === null && /^(Option|Command)$/.test(b.head[0])) {
      extra.unshift({ title: b.head[0] === "Option" ? "Options" : "Commands", list: [b] });
      continue;
    }
    if (b.type === "code" && title === null && description.length === 0) continue;
    target.push(b);
  }
  // A section starts a paragraph of its own.
  const body = (list) => roffBlocks(list).replace(/^\.PP\n/, "");
  out += ".SH DESCRIPTION\n" + body(description);
  const order = ["Commands", "Options", "Environment variables"];
  extra.sort((a, b) => order.indexOf(a.title) - order.indexOf(b.title));
  for (const e of extra) {
    if (e.title === "Exit status") continue;
    const name = e.title === "Environment variables" ? "ENVIRONMENT" : e.title.toUpperCase();
    out += `.SH ${name}\n` + body(e.list);
  }
  out += ".SH EXIT STATUS\n";
  for (const x of cmd.exit) out += `.TP\n${x.status}\n${roffEscape(sentence(x.summary))}\n`;
  out += ".SH SEE ALSO\n";
  const others = cmd.default ? spec.commands.filter((c) => !c.default).map((c) => `lus-${c.name}`) : ["lus"];
  out += others.map((p) => `.BR ${p} (1)`).join(",\n") + "\n";
  out += `.PP\nThe CLI page of the Lus manual, ${site}/manual/cli${cmd.default ? "" : `#lus-${cmd.name}`}, has the same text with links to the rest of the manual.\n`;
  return out;
}

