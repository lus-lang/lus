// The manual

/// The sections of the CLI page, as a map from the heading of each `##`
/// section to its lines.
function manualSections(text) {
  const sections = new Map();
  let current = null;
  for (const line of text.split("\n")) {
    const m = line.match(/^## (.*)$/);
    if (m) {
      current = [];
      sections.set(m[1], current);
    } else if (current) {
      current.push(line);
    }
  }
  return sections;
}

/// Splits the lines of a section into blocks: `heading`, `code`, `table`,
/// and `para`.
function blocks(lines) {
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (line.trim() === "") continue;
    if (line.startsWith("### ")) {
      out.push({ type: "heading", text: line.slice(4) });
    } else if (line.startsWith("```")) {
      const body = [];
      for (i++; i < lines.length && !lines[i].startsWith("```"); i++) body.push(lines[i]);
      out.push({ type: "code", lines: body });
    } else if (line.startsWith("|")) {
      const rows = [];
      for (; i < lines.length && lines[i].startsWith("|"); i++) rows.push(splitRow(lines[i]));
      i--;
      out.push({ type: "table", head: rows[0], rows: rows.slice(2) });
    } else {
      const body = [];
      for (; i < lines.length && lines[i].trim() !== "" && !/^(###|```|\|)/.test(lines[i]); i++) body.push(lines[i]);
      i--;
      out.push({ type: "para", text: body.join(" ") });
    }
  }
  return out;
}

function splitRow(line) {
  const cells = [];
  let cell = "";
  const inner = line.trim().replace(/^\|/, "").replace(/\|$/, "");
  for (let i = 0; i < inner.length; i++) {
    if (inner[i] === "\\" && inner[i + 1] === "|") {
      cell += "|";
      i++;
    } else if (inner[i] === "|") {
      cells.push(cell.trim());
      cell = "";
    } else {
      cell += inner[i];
    }
  }
  cells.push(cell.trim());
  return cells;
}

/// The option names of a table cell such as "`-P perm`, `--pledge perm`".
function cellNames(cell) {
  return [...cell.matchAll(/`([^`]+)`/g)].map((m) => m[1].split(" ")[0]);
}

