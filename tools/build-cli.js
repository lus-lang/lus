function outputs(root = ROOT) {
  const spec = loadSpec(root);
  const perms = readPermissions(root);
  const sections = manualSections(read(root, MANUAL));
  const site = JSON.parse(read(root, "packaging/project.json")).site;
  const files = [
    ["runtime/src/tools/usage.zig", usageZig(spec)],
    ["packaging/share/bash-completion/completions/lus", bash(spec, perms)],
    ["packaging/share/zsh/site-functions/_lus", zsh(spec, perms)],
    ["packaging/share/fish/vendor_completions.d/lus.fish", fish(spec, perms)],
    ["packaging/share/powershell/lus.ps1", powershell(spec, perms)],
  ];
  for (const c of spec.commands) {
    if (!sections.has(c.default ? "lus" : `lus ${c.name}`)) continue;
    files.push([`packaging/share/man/man1/${c.default ? "lus" : `lus-${c.name}`}.1`, manPage(spec, c, sections, site)]);
  }
  return files;
}

/// The source files whose parser reads the options of each command.
const PARSERS = {
  run: "runtime/src/main.zig",
  lsp: "packages/language-server/main.lus",
};
const parserFile = (name) => PARSERS[name] ?? `runtime/src/tools/${name}.zig`;

/// The options that the parser of a command recognizes: every string
/// literal that looks like an option, with `--name=` read as `--name`.
/// The option table of main.zig lists `.short` and `.long` fields.
function parsedOptions(root, cmd) {
  const src = read(root, parserFile(cmd.name));
  const found = new Set();
  if (cmd.default) {
    const table = src.match(/const options = \[_\]OptSpec\{([\s\S]*?)\n\};/);
    if (!table) throw new Error("runtime/src/main.zig has no options table");
    for (const m of table[1].matchAll(/\.short = "(.)"/g)) found.add(`-${m[1]}`);
    for (const m of table[1].matchAll(/\.long = "([a-z-]+)"/g)) found.add(`--${m[1]}`);
    return found;
  }
  for (const m of src.matchAll(/"(--?[A-Za-z][A-Za-z0-9-]*)=?"/g)) found.add(m[1]);
  if (hasHelp(cmd)) {
    found.delete("-h");
    found.delete("--help");
  }
  return found;
}

function checks(root = ROOT) {
  const spec = loadSpec(root);
  const problems = [];
  const sections = manualSections(read(root, MANUAL));
  const names = new Set();
  for (const c of spec.commands) {
    if (names.has(c.name)) problems.push(`${SOURCE}: the command ${c.name} appears twice`);
    names.add(c.name);
    if (!c.summary || !c.exit?.length) problems.push(`${SOURCE}: the command ${c.name} needs a summary and its exit statuses`);
    const declared = new Set();
    for (const o of (c.options ?? []).concat((c.subcommands ?? []).flatMap((s) => s.options ?? []))) {
      for (const n of o.names) {
        if (!/^(-[A-Za-z]|--[a-z][a-z0-9-]*)$/.test(n)) problems.push(`${SOURCE}: ${c.name} has a malformed option name ${n}`);
        declared.add(n);
      }
      if (o.value && o.value.kind === "enum" && !o.value.values?.length) problems.push(`${SOURCE}: ${c.name} ${o.names[0]} is an enum without values`);
    }
    // Both directions between the source and the parser.
    const parsed = parsedOptions(root, c);
    for (const n of declared) if (!parsed.has(n)) problems.push(`${parserFile(c.name)}: the parser of lus ${c.name} does not recognize ${n}, which ${SOURCE} lists`);
    for (const n of parsed) if (!declared.has(n)) problems.push(`${SOURCE}: lus ${c.name} accepts ${n}, which the source does not list`);
    // The manual names the same options and the same synopsis.
    const heading = c.default ? "lus" : `lus ${c.name}`;
    const section = sections.get(heading);
    if (!section) {
      problems.push(`${MANUAL}: no section ## ${heading}`);
      continue;
    }
    const list = blocks(section);
    const code = list.find((b) => b.type === "code");
    const want = synopsisLines(spec, c);
    if (!code || code.lines.join("\n") !== want.join("\n")) problems.push(`${MANUAL}: the synopsis of ## ${heading} must read\n${want.join("\n")}`);
    const optTable = list.find((b) => b.type === "table" && b.head[0] === "Option");
    const documented = new Set(optTable ? optTable.rows.flatMap((r) => cellNames(r[0])) : []);
    const visible = new Set(visibleOptions(c, false).flatMap((o) => o.names).concat((c.subcommands ?? []).flatMap((s) => (s.options ?? []).flatMap((o) => o.names))));
    for (const s of c.separators ?? []) visible.add(s.name);
    if (c.name !== "version") {
      for (const n of visible) if (!documented.has(n)) problems.push(`${MANUAL}: ## ${heading} does not document ${n}`);
      for (const n of documented) if (!visible.has(n)) problems.push(`${MANUAL}: ## ${heading} documents ${n}, which ${SOURCE} does not list`);
    }
    if (c.default) {
      const cmdTable = list.find((b) => b.type === "table" && b.head[0] === "Command");
      const listed = new Set(cmdTable ? cmdTable.rows.flatMap((r) => cellNames(r[0])) : []);
      for (const other of spec.commands) if (!listed.has(other.name)) problems.push(`${MANUAL}: the table of commands of ## lus does not list ${other.name}`);
      const envTable = list.find((b) => b.type === "table" && b.head[0] === "Variable");
      const vars = new Set(envTable ? envTable.rows.flatMap((r) => cellNames(r[0])) : []);
      const declaredVars = new Set(spec.environment.map((e) => e.name));
      for (const v of declaredVars) if (!vars.has(v)) problems.push(`${MANUAL}: ## lus does not document ${v}`);
      for (const v of vars) if (!declaredVars.has(v)) problems.push(`${MANUAL}: ## lus documents ${v}, which ${SOURCE} does not list`);
    }
  }
  return problems;
}

function main() {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [rel, text] of outputs()) {
    const file = path.join(ROOT, rel);
    const old = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (old === text) continue;
    if (check) {
      console.error(`${rel} is out of date. Run node tools/build-cli.js`);
      stale++;
    } else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
      console.log(`Wrote ${rel}`);
    }
  }
  const problems = checks();
  for (const p of problems) console.error(p);
  if (stale || problems.length) process.exit(1);
  if (check) console.log("Checked the usage text, the completions, the man pages, the parsers, and the manual against spec/tools/cli.json");
}

if (require.main === module) main();

