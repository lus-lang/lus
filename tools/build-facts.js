#!/usr/bin/env node
// Copies the facts that several parts of the repository state from their
// one source to every file that states them, and checks the files that
// state a fact by hand. Run: node tools/build-facts.js [--check]
//
// - The version of Lus comes from runtime/build.zig.zon. The language
//   server, the WebAssembly package, and the Visual Studio Code extension
//   receive a copy.
// - The reserved words come from `keywords` in runtime/src/syntax/token.zig.
//   The language server receives a copy, and the TextMate template and the
//   grammar (spec/language/grammar.md, section 1.3) must name every one.
// - The address of the site and of the repository come from
//   packaging/project.json, which the JavaScript of the repository imports.
//   The files that cannot import it must state the same addresses.
// - The permissions come from `builtin_caps` in runtime/src/vm/pledge.zig.
//   The manual (packages/site/src/manual/permissions.mdx) must name every
//   one, and every `pledges` entry of spec/stdlib must be one of them.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const read = (root, rel) => fs.readFileSync(path.join(root, rel), "utf8");
const GENERATED = "-- Generated by tools/build-facts.js. Do not edit.\n";

/// The version in runtime/build.zig.zon, such as 2.0.0-dev.
function readVersion(root = ROOT) {
  const m = read(root, "runtime/build.zig.zon").match(/\.version\s*=\s*"([^"]+)"/);
  if (!m) throw new Error("runtime/build.zig.zon has no .version");
  return m[1];
}

/// The reserved words in the order of the lexer.
function readKeywords(root = ROOT) {
  const m = read(root, "runtime/src/syntax/token.zig").match(/pub const keywords = \[_\]\[\]const u8\{([^}]*)\}/);
  if (!m) throw new Error("runtime/src/syntax/token.zig has no keywords array");
  return [...m[1].matchAll(/"([a-z]+)"/g)].map((x) => x[1]);
}

/// The permissions that the runtime declares: each base name and each
/// `base:part`.
function readPermissions(root = ROOT) {
  const m = read(root, "runtime/src/vm/pledge.zig").match(/const builtin_caps = \[_\]Capability\{([\s\S]*?)\n\};/);
  if (!m) throw new Error("runtime/src/vm/pledge.zig has no builtin_caps");
  const names = [];
  for (const line of m[1].split("\n")) {
    const base = line.match(/\.name = "([a-z]+)"/);
    if (!base) continue;
    names.push(base[1]);
    const subs = line.match(/\.subs = &\.\{([^}]*)\}/);
    if (subs) for (const sub of subs[1].matchAll(/"([a-z]+)"/g)) names.push(`${base[1]}:${sub[1]}`);
  }
  return names;
}

/// The files outside JavaScript that state an address of the project, and
/// the address each must contain.
const ADDRESS_FILES = [
  ["runtime/src/tools/version.zig", "site"],
  ["packaging/install/install.sh", "site"],
  ["packaging/install/lus.iss", "site"],
  ["tools/release-index.mjs", "site"],
  ["packages/vscode/package.json", "repository"],
  [".agents/.claude-plugin/plugin.json", "site"],
  [".agents/.claude-plugin/plugin.json", "repository"],
];

/// The version without its prerelease part. The Visual Studio Code
/// marketplace accepts numbers only and marks prereleases with a flag.
function release(version) {
  return version.replace(/-.*$/, "");
}

/// The package.json `text` with its top-level version set to `version`,
/// keeping every other byte as it is.
function withVersion(text, version) {
  const re = /^(\s*"version"\s*:\s*)"[^"]*"/m;
  if (!re.test(text)) throw new Error("package.json has no version field");
  return text.replace(re, `$1${JSON.stringify(version)}`);
}

function luaList(words) {
  const lines = [];
  for (let i = 0; i < words.length; i += 8) lines.push("  " + words.slice(i, i + 8).map((w) => JSON.stringify(w)).join(", ") + ",");
  return "{\n" + lines.join("\n") + "\n}";
}

/// The files to write and their contents.
function outputs(root = ROOT) {
  const version = readVersion(root);
  return [
    ["packages/language-server/version.lus", GENERATED + `return ${JSON.stringify(version)}\n`],
    ["packages/language-server/analysis/keywords.lus", GENERATED + "-- The reserved words of Lus, in the order of the lexer.\nreturn " + luaList(readKeywords(root)) + "\n"],
    ["packages/wasm/package.json", withVersion(read(root, "packages/wasm/package.json"), version)],
    ["packages/vscode/package.json", withVersion(read(root, "packages/vscode/package.json"), release(version))],
  ];
}

/// The problems of the files that state a fact by hand.
function checks(root = ROOT) {
  const problems = [];
  const keywords = readKeywords(root);
  // Every reserved word is a whole word of some alternation in a pattern
  // of the TextMate template.
  const template = read(root, "packages/textmate/lus.tmLanguage.template.json");
  for (const kw of keywords) {
    if (!new RegExp(`[(|?:]${kw}[|)]`).test(template)) problems.push(`packages/textmate/lus.tmLanguage.template.json highlights no reserved word ${kw}`);
  }
  // The grammar lists the reserved words in the order of the lexer.
  const grammar = read(root, "spec/language/grammar.md");
  const block = grammar.match(/The reserved words are exactly the entries of `token\.keywords`, in this order:\n\n```\n([\s\S]*?)```/);
  const listed = block ? block[1].split(/\s+/).filter(Boolean) : [];
  if (listed.join(" ") !== keywords.join(" ")) problems.push("spec/language/grammar.md, section 1.3, lists other reserved words than runtime/src/syntax/token.zig");
  // The addresses of the project.
  const project = JSON.parse(read(root, "packaging/project.json"));
  for (const [rel, which] of ADDRESS_FILES) {
    if (!read(root, rel).includes(project[which])) problems.push(`${rel} does not state the ${which} address ${project[which]} of packaging/project.json`);
  }
  // The permissions.
  const permissions = readPermissions(root);
  const manual = read(root, "packages/site/src/manual/permissions.mdx");
  for (const name of permissions) {
    if (!manual.includes("`" + name + "`")) problems.push(`packages/site/src/manual/permissions.mdx does not name the permission ${name}`);
  }
  const known = new Set(permissions);
  const walk = (dir) => {
    for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
      const rel = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(rel);
      else if (entry.name.endsWith(".md")) {
        const m = read(root, rel).match(/^pledges:\s*\[([^\]]*)\]/m);
        if (!m) continue;
        for (const p of m[1].matchAll(/"([^"]+)"/g)) {
          const name = p[1].split("=")[0];
          if (!known.has(name)) problems.push(`${rel} names the unknown permission ${p[1]}`);
        }
      }
    }
  };
  walk("spec/stdlib");
  return problems;
}

function main() {
  const check = process.argv.includes("--check");
  let failed = 0;
  for (const [rel, text] of outputs()) {
    const file = path.join(ROOT, rel);
    const old = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (old === text) continue;
    if (check) {
      console.error(`${rel} is stale. Run node tools/build-facts.js`);
      failed++;
    } else {
      fs.writeFileSync(file, text);
      console.log(`Wrote ${rel}`);
    }
  }
  for (const p of checks()) {
    console.error(p);
    failed++;
  }
  if (failed > 0) process.exitCode = 1;
  else if (check) console.log("Checked the version, the reserved words, the addresses, and the permissions");
}

if (require.main === module) main();

module.exports = { readVersion, readKeywords, readPermissions, release, withVersion, outputs, checks };
