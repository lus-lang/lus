#!/bin/sh
# Installs the Lus harness for Pi: the `lush` command, which starts the Pi
# coding agent with the Lus extensions and theme loaded.
#
#   sh packages/harness/install.sh                    from a checkout
#   curl -fsSL https://lus.dev/harness.sh | sh        anywhere else
#
# The harness ships only its own files. Pi stays a separate install: the
# script uses the `pi` on PATH, or installs Pi through its own installer at
# pi.dev after asking. Run from a checkout of the Lus repository, the
# launcher points at the checkout, so a `git pull` updates the harness. Run
# from anywhere else, the script downloads the source archive of a Lus
# release from GitHub and keeps the three directories the harness reads,
# packages/harness, packages/language-server, and .agents, under
# $LUS_HOME/harness/<ref>. The launcher goes into $LUS_HOME/bin, beside the
# `lus` that the Lus installer manages.

set -u

REPO="lus-lang/lus"
PI_INSTALLER="https://pi.dev/install.sh"

info() { printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die()  { printf 'error: %s\n' "$*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1; }

usage() {
  cat <<EOF
The Lus harness installer.

Usage:
  sh install.sh [--ref REF] [--home DIR] [--name NAME] [--yes] [--no-pi]
  sh install.sh --uninstall [--home DIR] [--name NAME]

Options:
  --ref REF     the tag or branch whose harness to download, such as v2.0.0
                (env: LUS_HARNESS_REF). The default is the tag of the
                installed lus, or main for a development build. A checkout
                ignores it and uses its own files.
  --home DIR    the Lus home, default ~/.lus (env: LUS_HOME)
  --name NAME   the name of the launcher, default lush
  --yes         install Pi without asking when it is missing
  --no-pi       stop with an error when Pi is missing
  --uninstall   remove the launcher and the downloaded harness
  -h, --help    show this help

LUS_HARNESS_ARCHIVE names a local source archive of the repository to
install from in place of the download.

When piping to sh, pass options as environment variables:
  LUS_HARNESS_REF=v2.0.0 curl -fsSL https://lus.dev/harness.sh | sh
EOF
}

LUS_HOME=${LUS_HOME:-$HOME/.lus}
REF=${LUS_HARNESS_REF:-}
NAME=lush
PI_POLICY=ask
UNINSTALL=0

while [ $# -gt 0 ]; do
  case $1 in
    --ref) [ $# -ge 2 ] || die "--ref needs a value"; REF=$2; shift 2 ;;
    --ref=*) REF=${1#*=}; shift ;;
    --home) [ $# -ge 2 ] || die "--home needs a value"; LUS_HOME=$2; shift 2 ;;
    --home=*) LUS_HOME=${1#*=}; shift ;;
    --name) [ $# -ge 2 ] || die "--name needs a value"; NAME=$2; shift 2 ;;
    --name=*) NAME=${1#*=}; shift ;;
    --yes|-y) PI_POLICY=yes; shift ;;
    --no-pi) PI_POLICY=no; shift ;;
    --uninstall) UNINSTALL=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown option: $1 (see --help)" ;;
  esac
done

case $NAME in
  ''|*/*|.*) die "the launcher name must be a plain file name" ;;
esac

BIN_DIR=$LUS_HOME/bin
LAUNCHER=$BIN_DIR/$NAME
HARNESS_HOME=$LUS_HOME/harness

if [ "$UNINSTALL" = 1 ]; then
  if [ -f "$LAUNCHER" ] && grep -q 'Generated by the Lus harness installer' "$LAUNCHER"; then
    rm -f "$LAUNCHER"
    info "removed $LAUNCHER"
  fi
  if [ -d "$HARNESS_HOME" ]; then
    rm -rf "$HARNESS_HOME"
    info "removed $HARNESS_HOME"
  fi
  exit 0
fi

# ask QUESTION: true for yes. Reads the terminal, so it also works when the
# script itself arrives on standard input through a pipe.
ask() {
  [ -r /dev/tty ] || return 1
  printf '%s [y/N] ' "$1" >/dev/tty
  read -r answer </dev/tty || return 1
  case $answer in y|Y|yes|YES) return 0 ;; *) return 1 ;; esac
}

fetch() {
  if need curl; then
    curl -fsSL --proto '=https' --tlsv1.2 "$1" -o "$2"
  elif need wget; then
    wget -q --https-only -O "$2" "$1"
  else
    die "curl or wget is required to download $1"
  fi
}

# Pi. The harness runs inside the user's own Pi, with their settings and
# logins, so an existing install is always used as it is.
if ! need pi; then
  case $PI_POLICY in
    no) die "pi is not installed. Install it from https://pi.dev, then run this script again." ;;
    yes) ;;
    ask) ask "Pi is not installed. Install it now with its installer from pi.dev?" \
           || die "pi is required. Install it from https://pi.dev, then run this script again." ;;
  esac
  info "installing Pi from $PI_INSTALLER"
  tmp=$(mktemp "${TMPDIR:-/tmp}/pi-install.XXXXXX") || die "cannot create a temporary file"
  fetch "$PI_INSTALLER" "$tmp" || die "cannot download the Pi installer"
  sh "$tmp" || die "the Pi installer failed"
  rm -f "$tmp"
  # The Pi installer may place pi in a directory that this shell has not
  # put on PATH yet.
  for dir in "$HOME/.pi/bin" "$HOME/.local/bin"; do
    if [ -x "$dir/pi" ] && ! need pi; then PATH=$dir:$PATH; fi
  done
  need pi || die "Pi was installed, but pi is not on PATH. Open a new shell and run this script again."
fi
PI=$(command -v pi)

# Lus. The harness tools run the lus command, so the script checks that a
# Lus 2 runtime is installed and says how to get one.
wanted=${LUS_BIN:-}
LUS_BIN=
for candidate in "$wanted" "$BIN_DIR/lus" "$(command -v lus 2>/dev/null || true)"; do
  [ -n "$candidate" ] && [ -x "$candidate" ] || continue
  version=$("$candidate" -v 2>&1 | sed -n 's/^Lus \([^ ]*\).*/\1/p' | head -n 1)
  case $version in
    [2-9].*) LUS_BIN=$candidate; LUS_VERSION=$version; break ;;
  esac
done
if [ -z "$LUS_BIN" ]; then
  warn "no Lus 2 runtime found. Install one with: curl -fsSL https://lus.dev/install.sh | sh"
  LUS_VERSION=
fi

# The harness files: a checkout, or a download.
# Piped to sh, $0 names the shell and not a file, so only a script run from
# a file can be part of a checkout.
script_dir=
if [ -f "$0" ]; then
  script_dir=$(cd "$(dirname "$0")" 2>/dev/null && pwd || true)
fi
if [ -n "$script_dir" ] && [ -f "$script_dir/src/index.ts" ] \
  && [ -f "$script_dir/../language-server/main.lus" ] && [ -d "$script_dir/../../.agents/skills" ]; then
  HARNESS_DIR=$script_dir
  info "using the harness in $HARNESS_DIR"
else
  if [ -z "$REF" ]; then
    case $LUS_VERSION in
      ''|*-*) REF=main ;;
      *) REF=v$LUS_VERSION ;;
    esac
  fi
  case $REF in
    v[0-9]*) url="https://codeload.github.com/$REPO/tar.gz/refs/tags/$REF" ;;
    *) url="https://codeload.github.com/$REPO/tar.gz/refs/heads/$REF" ;;
  esac
  need tar || die "tar is required"
  work=$(mktemp -d "${TMPDIR:-/tmp}/lus-harness.XXXXXX") || die "cannot create a temporary directory"
  trap 'rm -rf "$work"' EXIT INT TERM HUP
  if [ -n "${LUS_HARNESS_ARCHIVE:-}" ]; then
    # A local source archive, for tests and offline installs.
    cp "$LUS_HARNESS_ARCHIVE" "$work/src.tar.gz" || die "cannot read $LUS_HARNESS_ARCHIVE"
  else
    info "downloading the harness of $REF"
    fetch "$url" "$work/src.tar.gz" || die "cannot download $url"
  fi
  mkdir "$work/src"
  tar -xzf "$work/src.tar.gz" -C "$work/src" --strip-components=1 || die "cannot unpack the archive"
  for part in packages/harness packages/language-server .agents; do
    [ -e "$work/src/$part" ] || die "the archive of $REF has no $part, so it predates the harness. Name a newer ref with --ref or LUS_HARNESS_REF."
  done
  dest=$HARNESS_HOME/$REF
  rm -rf "$dest.tmp"
  mkdir -p "$dest.tmp/packages" || die "cannot create $dest"
  cp -R "$work/src/packages/harness" "$work/src/packages/language-server" "$dest.tmp/packages/" \
    && cp -R "$work/src/.agents" "$dest.tmp/" || die "cannot copy the harness into $dest"
  rm -rf "$dest"
  mv "$dest.tmp" "$dest" || die "cannot move the harness into $dest"
  HARNESS_DIR=$dest/packages/harness
  info "installed the harness into $dest"
fi

mkdir -p "$BIN_DIR" || die "cannot create $BIN_DIR"
if [ -e "$LAUNCHER" ] && ! grep -q 'Generated by the Lus harness installer' "$LAUNCHER" 2>/dev/null; then
  die "$LAUNCHER exists and was not written by this installer. Choose another name with --name."
fi

# The launcher keeps the user's choice of theme when the command line names
# one, and otherwise follows the terminal between the light and dark Lus
# themes.
cat > "$LAUNCHER.tmp" <<EOF
#!/bin/sh
# Generated by the Lus harness installer. Run the installer again to update
# it, or with --uninstall to remove it.
harness='$HARNESS_DIR'
pi='$PI'
command -v pi >/dev/null 2>&1 && pi=\$(command -v pi)
for arg in "\$@"; do
  case \$arg in --use-theme|--use-theme=*) exec "\$pi" -e "\$harness" "\$@" ;; esac
done
exec "\$pi" -e "\$harness" --use-theme "\${LUS_HARNESS_THEME:-lus-light/lus}" "\$@"
EOF
chmod +x "$LAUNCHER.tmp" && mv "$LAUNCHER.tmp" "$LAUNCHER" || die "cannot write $LAUNCHER"
info "wrote $LAUNCHER"

case :$PATH: in
  *:"$BIN_DIR":*) ;;
  *) info "add $BIN_DIR to PATH to run $NAME from any directory" ;;
esac
info "run $NAME in a project to start Pi with the Lus harness"
