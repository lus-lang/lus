#!/usr/bin/env node
// Generates lus/src/ltzdata.c: the embedded, zstd-compressed IANA tzdata blob
// consumed by the `time` module for named-zone lookup.
//
// Usage: node scripts/gen-tzdata.js [zoneinfo_dir] [out_c_file]
//   zoneinfo_dir defaults to /usr/share/zoneinfo (already-compiled TZif files;
//   no `zic` required). out_c_file defaults to lus/src/ltzdata.c.
//
// The blob is a flat, indexed container (all integers little-endian):
//   "LTZ1"                       magic
//   u8  version_len, version     e.g. "2026b"
//   u32 zone_count
//   repeat zone_count, sorted by name:
//     u16 name_len, name (e.g. "America/New_York")
//     u32 tzif_len,  tzif bytes  (raw RFC 8536 TZif, copied verbatim)
// The whole container is compressed with `zstd -19`; the runtime decompresses
// it once per interpreter state on first zone access (see ltimelib.c).

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ZONEINFO = process.argv[2] || "/usr/share/zoneinfo";
const OUT = process.argv[3] || path.join(__dirname, "..", "lus", "src", "ltzdata.c");

// Collect every TZif file under the tree, skipping the right/ (leap-second) and
// posix/ variants which duplicate the mainline zones.
function collect(dir, root, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = path.relative(root, full);
    if (rel.startsWith("right" + path.sep) || rel.startsWith("posix" + path.sep))
      continue;
    if (entry.isDirectory()) {
      collect(full, root, out);
    } else if (entry.isFile()) {
      const fd = fs.openSync(full, "r");
      const magic = Buffer.alloc(4);
      const n = fs.readSync(fd, magic, 0, 4, 0);
      if (n === 4 && magic.toString("latin1") === "TZif") {
        const data = fs.readFileSync(full);
        out.push({ name: rel.split(path.sep).join("/"), data });
      }
      fs.closeSync(fd);
    }
  }
}

function detectVersion(root) {
  // tzdata.zi carries "# version 2026b" on its first line.
  try {
    const zi = fs.readFileSync(path.join(root, "tzdata.zi"), "latin1");
    const m = zi.match(/#\s*version\s+(\S+)/);
    if (m) return m[1];
  } catch (_) {}
  try {
    return fs.readFileSync(path.join(root, "+VERSION"), "latin1").trim();
  } catch (_) {}
  return "unknown";
}

const zones = [];
collect(ZONEINFO, ZONEINFO, zones);
zones.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
const version = detectVersion(ZONEINFO);

// Assemble the uncompressed container.
const parts = [];
parts.push(Buffer.from("LTZ1", "latin1"));
const vbuf = Buffer.from(version, "latin1");
const vlen = Buffer.alloc(1);
vlen.writeUInt8(vbuf.length, 0);
parts.push(vlen, vbuf);
const count = Buffer.alloc(4);
count.writeUInt32LE(zones.length, 0);
parts.push(count);
for (const z of zones) {
  const nb = Buffer.from(z.name, "latin1");
  const nl = Buffer.alloc(2);
  nl.writeUInt16LE(nb.length, 0);
  const dl = Buffer.alloc(4);
  dl.writeUInt32LE(z.data.length, 0);
  parts.push(nl, nb, dl, z.data);
}
const raw = Buffer.concat(parts);

// Compress via the zstd CLI (avoids depending on a specific Node zstd binding).
const compressed = execFileSync("zstd", ["-19", "-c"], {
  input: raw,
  maxBuffer: 1 << 30,
});

// Emit the C source.
let out = `/*
** ltzdata.c
** AUTO-GENERATED by scripts/gen-tzdata.js. DO NOT EDIT.
** Embedded IANA tzdata ${version}: ${zones.length} zones,
** ${raw.length} bytes raw, ${compressed.length} bytes zstd-compressed.
*/

#include "ltzdata.h"

const char lus_tzdata_version[] = "${version}";
const unsigned long lus_tzdata_raw_len = ${raw.length}UL;
const unsigned long lus_tzdata_z_len = ${compressed.length}UL;

const unsigned char lus_tzdata_z[] = {
`;
const bytes = [];
for (let i = 0; i < compressed.length; i++) {
  bytes.push("0x" + compressed[i].toString(16).padStart(2, "0"));
}
for (let i = 0; i < bytes.length; i += 16) {
  out += "  " + bytes.slice(i, i + 16).join(", ") + ",\n";
}
out += "};\n";

fs.writeFileSync(OUT, out);
console.log(
  `Wrote ${OUT}: tzdata ${version}, ${zones.length} zones, ` +
    `${raw.length} -> ${compressed.length} bytes (zstd -19).`
);
