#!/usr/bin/env node
// Generates lus/src/lwinzones.c: the CLDR Windows-to-IANA time-zone mapping used
// by time.localzone() on Windows.
//
// Usage: node scripts/gen-winzones.js <windowsZones.xml> [out_c_file]
//   Fetch the input from CLDR, e.g.
//   https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml
// (see scripts/update-winzones.sh). CLDR data is under the Unicode license,
// which permits redistribution.

const fs = require("fs");
const path = require("path");

const XML = process.argv[2];
const OUT = process.argv[3] || path.join(__dirname, "..", "lus", "src", "lwinzones.c");
if (!XML) {
  console.error("usage: gen-winzones.js <windowsZones.xml> [out.c]");
  process.exit(1);
}

const xml = fs.readFileSync(XML, "utf-8");
// Take the default (territory="001") mapping: one primary IANA zone per Windows
// zone key. The `type` attribute may list several zones; the first is primary.
const re =
  /<mapZone\s+other="([^"]+)"\s+territory="001"\s+type="([^"]+)"/g;
const pairs = [];
let m;
while ((m = re.exec(xml)) !== null) {
  pairs.push({ win: m[1], iana: m[2].split(/\s+/)[0] });
}
pairs.sort((a, b) => (a.win < b.win ? -1 : a.win > b.win ? 1 : 0));

let out = `/*
** lwinzones.c
** AUTO-GENERATED by scripts/gen-winzones.js. DO NOT EDIT.
** CLDR Windows-to-IANA time-zone mapping (${pairs.length} default entries),
** used by time.localzone() on Windows.
*/

#include "lwinzones.h"

#if defined(LUS_PLATFORM_WINDOWS)

#include <string.h>

const char *lus_windows_to_iana(const char *key) {
  static const struct {
    const char *win;
    const char *iana;
  } map[] = {
`;
for (const p of pairs) {
  out += `      {${JSON.stringify(p.win)}, ${JSON.stringify(p.iana)}},\n`;
}
out += `  };
  for (unsigned i = 0; i < sizeof(map) / sizeof(map[0]); i++)
    if (strcmp(map[i].win, key) == 0)
      return map[i].iana;
  return 0;
}

#else

/* Keep this a non-empty translation unit on platforms without the mapping. */
typedef int lus_winzones_no_mapping;

#endif
`;
fs.writeFileSync(OUT, out);
console.log(`Wrote ${OUT}: ${pairs.length} Windows->IANA mappings.`);
