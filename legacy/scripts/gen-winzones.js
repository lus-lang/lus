#!/usr/bin/env node
// Generates lus/src/lwinzones.c: the CLDR Windows-to-IANA time-zone mapping used
// by time.localzone() on Windows.
//
// Usage: node scripts/gen-winzones.js <windowsZones.json-or-xml> [out_c_file]
//   [source_version]
// See scripts/update-winzones.sh for the pinned CLDR source. CLDR data is
// under the Unicode license, which permits redistribution.

const fs = require("fs");
const path = require("path");

const INPUT = process.argv[2];
const OUT = process.argv[3] || path.join(__dirname, "..", "lus", "src", "lwinzones.c");
let sourceVersion = process.argv[4] || "unknown";
if (!INPUT) {
  console.error("usage: gen-winzones.js <windowsZones.json-or-xml> [out.c] [version]");
  process.exit(1);
}

const input = fs.readFileSync(INPUT, "utf-8");
// Take the default territory mapping. It supplies one primary IANA zone per
// Windows zone key. A type value may list several zones. The first is primary.
const pairs = [];
if (input.trimStart().startsWith("{")) {
  const data = JSON.parse(input);
  if (sourceVersion === "unknown")
    sourceVersion = data.supplemental?.version?._cldrVersion || "unknown";
  const entries = data.supplemental?.windowsZones?.mapTimezones;
  if (!Array.isArray(entries))
    throw new Error("CLDR JSON has no windowsZones.mapTimezones array");
  for (const entry of entries) {
    const zone = entry.mapZone;
    if (zone?._territory === "001")
      pairs.push({ win: zone._other, iana: zone._type.split(/\s+/)[0] });
  }
} else {
  const re =
    /<mapZone\s+other="([^"]+)"\s+territory="001"\s+type="([^"]+)"/g;
  let match;
  while ((match = re.exec(input)) !== null)
    pairs.push({ win: match[1], iana: match[2].split(/\s+/)[0] });
}
if (pairs.length === 0)
  throw new Error("CLDR input contains no default Windows zone mappings");
pairs.sort((a, b) => (a.win < b.win ? -1 : a.win > b.win ? 1 : 0));

let out = `/*
** lwinzones.c
** AUTO-GENERATED by scripts/gen-winzones.js. DO NOT EDIT.
** CLDR ${sourceVersion} Windows-to-IANA time-zone mapping
** (${pairs.length} default entries),
** used by time.localzone() on Windows.
*/

#include "lwinzones.h"

#if defined(LUS_PLATFORM_WINDOWS)

#include <string.h>

const char *lus_windows_to_iana(const char *key) {
  static const struct {
    const char *win;
    const char *iana;
  } map[] = {
`;
for (const p of pairs) {
  out += `      {${JSON.stringify(p.win)}, ${JSON.stringify(p.iana)}},\n`;
}
out += `  };
  for (unsigned i = 0; i < sizeof(map) / sizeof(map[0]); i++)
    if (strcmp(map[i].win, key) == 0)
      return map[i].iana;
  return 0;
}

#else

/* Keep this a non-empty translation unit on platforms without the mapping. */
typedef int lus_winzones_no_mapping;

#endif
`;
fs.writeFileSync(OUT, out);
console.log(`Wrote ${OUT}: ${pairs.length} Windows->IANA mappings.`);
